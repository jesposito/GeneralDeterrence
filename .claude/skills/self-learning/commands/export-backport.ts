import type { AsyncResult } from "../types/result";
import type { AhaCard } from "../types/aha-card";
import type { Signal } from "../types/signal";
import type { BackportRecord, BackportChange, BackportManifest } from "../types/backport";
import {
  AHA_CARD_START_MARKER,
  AHA_CARD_END_MARKER,
  AHA_FILE_HEADER_MARKER,
} from "../types/backport";
import { MIN_BACKPORT_SCORE } from "../types/signal";
import {
  findRepoRoot,
  getProjectStore,
  ensureStoreDirs,
  getStorePath,
  FILES,
  safeUserSlug,
} from "../lib/store";
import { readJsonl, appendJsonl, firstAndLatestById } from "../lib/jsonl";
import { backportId, sigId } from "../lib/id-generator";
import { isoNow } from "../lib/timestamp";
